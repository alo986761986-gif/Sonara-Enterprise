    @classmethod
    def generate_pattern(cls, genre: str, seed: int = 42) -> Dict[str, Any]:
        """Generates a procedural, genre-authentic 16-step pattern with micro-timing humanization."""
        genre_key = genre.lower()
        base = cls.GENRE_PATTERNS.get(genre_key, cls.GENRE_PATTERNS["melodic house"])

        rng = random.Random(seed)

        # Procedural variation: slightly shift or add ghost notes while maintaining strict genre rules
        kick_pattern = list(base["kick"])
        snare_pattern = list(base["snare"])
        hihat_pattern = list(base["hihat"])
        perc_pattern = list(base["perc"])
        bass_pattern = list(base["bass"])

        # Inject subtle seed-based velocity variation (Humanization)
        for i in range(16):
            if hihat_pattern[i] > 0.0:
                hihat_pattern[i] = max(0.2, min(1.0, round(hihat_pattern[i] + rng.uniform(-0.08, 0.08), 2)))
            if perc_pattern[i] > 0.0:
                perc_pattern[i] = max(0.2, min(1.0, round(perc_pattern[i] + rng.uniform(-0.1, 0.1), 2)))
            if bass_pattern[i] > 0.0:
                bass_pattern[i] = max(0.3, min(1.0, round(bass_pattern[i] + rng.uniform(-0.05, 0.05), 2)))

        # Micro-timing offsets in milliseconds per step (deterministic humanization)
        timing_offsets_ms = [round(rng.uniform(-2.5, 2.5) if i % 2 == 1 else 0.0, 2) for i in range(16)]

        return {
            "genre": genre,
            "seed": seed,
            "swing_pct": base["swing"],
            "step_count": 16,
            "patterns": {
                "kick": kick_pattern,
                "snare": snare_pattern,
                "hihat": hihat_pattern,
                "percussion": perc_pattern,
                "bass": bass_pattern
            },
            "chords": base["chords"],
            "timing_offsets_ms": timing_offsets_ms,
            "status": "PATTERN_GENERATED_SUCCESS"
        }

